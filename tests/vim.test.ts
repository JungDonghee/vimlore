import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Vim } from '../src/core/vim/engine.ts';
import { tokenize } from '../src/core/vim/keys.ts';
import { CASES } from '../tools/cases.ts';
import { checkGoal, goalLabel, collectPositions } from '../src/core/game/goals.ts';
import { Session, parseStart } from '../src/core/game/session.ts';
import { Buffer } from '../src/core/vim/buffer.ts';
import type { Stage } from '../src/core/game/types.ts';

interface Expected {
  lines: string[];
  cursor: [number, number];
}

const expected: Expected[] = JSON.parse(readFileSync(new URL('./vim-expected.json', import.meta.url), 'utf8'));

// ---------------------------------------------------------------------------
// Engine fidelity: the snapshot was generated by running a real `vim -u NONE`.
// Regenerate with: node --experimental-strip-types tools/oracle-diff.ts --emit
// ---------------------------------------------------------------------------
test('engine matches real vim on the oracle corpus', () => {
  assert.equal(expected.length, CASES.length);
  CASES.forEach((c, i) => {
    const v = new Vim({ text: c.text, cursor: { line: (c.cursor?.[0] ?? 1) - 1, col: c.cursor?.[1] ?? 0 } });
    v.feedString(c.keys);
    assert.deepEqual(v.buf.lines, expected[i].lines, `${c.name}: buffer`);
    assert.equal(v.cursor.line + 1, expected[i].cursor[0], `${c.name}: cursor line`);
    assert.equal(v.cursor.col, expected[i].cursor[1], `${c.name}: cursor col`);
  });
});

test('key tokenizer handles special keys', () => {
  assert.deepEqual(tokenize('ci"x<Esc>'), ['c', 'i', '"', 'x', '<Esc>']);
  assert.deepEqual(tokenize(':%s/a/b/g<CR>'), [':', '%', 's', '/', 'a', '/', 'b', '/', 'g', '<CR>']);
  assert.deepEqual(tokenize('<C-v>I'), ['<C-v>', 'I']);
});

test('buffer index round-trips', () => {
  const b = new Buffer('abc\ndefg\n\nhi');
  for (let line = 0; line < b.lineCount; line++) {
    for (let col = 0; col <= b.line(line).length; col++) {
      const p = b.pos(b.idx({ line, col }));
      assert.deepEqual({ line: p.line, col: p.col }, { line, col });
    }
  }
});

// ---------------------------------------------------------------------------
// Undo / repeat / macros
// ---------------------------------------------------------------------------
test('undo restores before a change session', () => {
  const v = new Vim({ text: 'hello world' });
  v.feedString('ciwX<Esc>');
  assert.equal(v.text, 'X world');
  v.feedString('u');
  assert.equal(v.text, 'hello world');
});

test('dot repeat replays the full change', () => {
  const v = new Vim({ text: 'aa bb cc' });
  v.feedString('cwX<Esc>w.');
  assert.equal(v.text, 'X X cc');
});

test('macro records and replays', () => {
  const v = new Vim({ text: 'a\nb\nc' });
  v.feedString('qaIx<Esc>jq');
  v.feedString('@a');
  assert.equal(v.text, 'xa\nxb\nc');
});

test('search + n lands on hits', () => {
  const v = new Vim({ text: 'one two one two' });
  v.feedString('/one<CR>');
  assert.deepEqual(v.cursor, { line: 0, col: 8 });
  v.feedString('n');
  assert.deepEqual(v.cursor, { line: 0, col: 0 });
});

test('ex substitute and global delete', () => {
  const v = new Vim({ text: 'cat\ncat\ncat' });
  v.feedString(':%s/cat/dog/g<CR>');
  assert.equal(v.text, 'dog\ndog\ndog');
  const w = new Vim({ text: 'keep\ndrop\nkeep' });
  w.feedString(':g/drop/d<CR>');
  assert.equal(w.text, 'keep\nkeep');
});

