test('change that opens insert clears the pending operator', () => {
  const v = new Vim({ text: 'one two three' });
  v.feedString('c{X<Esc>');
  v.feedString('u');
  assert.equal(v.text, 'one two three');
});

test('visual delete then undo restores the selection start (feedkeys Vim)', () => {
  const a = new Vim({ text: '  indented' });
  a.feedString('vbd');
  a.feedString('u');
  assert.equal(a.text, '  indented');
  assert.deepEqual(a.cursor, { line: 0, col: 0 });

  const b = new Vim({ text: 'foo bar\nbaz qux' });
  b.cursor = { line: 1, col: 1 };
  b.feedString('Vjdu');
  assert.equal(b.text, 'foo bar\nbaz qux');
  assert.deepEqual(b.cursor, { line: 1, col: 0 });
});

test('visual-line change then undo lands on column 0 (feedkeys Vim)', () => {
  const v = new Vim({ text: 'one two three' });
  v.feedString('VjcX<Esc>u');
  assert.equal(v.text, 'one two three');
  assert.deepEqual(v.cursor, { line: 0, col: 0 });
});

test('whole-line charwise yanks are linewise registers', () => {
  const a = new Vim({ text: 'a\n\nb\n\nc' });
  a.feedString('y)');
  assert.equal(a.registers.get('"')?.text, 'a\n');
  assert.equal(a.registers.get('"')?.linewise, true);

  const b = new Vim({ text: 'a\n\nb\n\nc' });
  b.feedString('2yw');
  assert.equal(b.registers.get('"')?.text, 'a\n\n');
  assert.equal(b.registers.get('"')?.linewise, true);
});

test('undo restores before a change session', () => {
  const v = new Vim({ text: 'hello world' });
  v.feedString('ciwX<Esc>');
  assert.equal(v.text, 'X world');
  v.feedString('u');
  assert.equal(v.text, 'hello world');
  v.feedString(':later 1<CR>');
  assert.equal(v.text, 'X world');
  v.feedString(':earlier 1<CR>');
  assert.equal(v.text, 'hello world');
});

