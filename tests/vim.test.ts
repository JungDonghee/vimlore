test('parseStart replaces @ without shifting the grid', () => {
  const r = parseStart('|..@..|\n+-----+', '.');
  assert.equal(r.text, '|.....|\n+-----+');
  assert.deepEqual({ line: r.line, col: r.col }, { line: 0, col: 3 });
  assert.equal(r.text.split('\n')[0].length, 7);
});

test('goals: exact ignores trailing whitespace', () => {
  const v = new Vim({ text: 'a  \nb' });
  assert.equal(checkGoal({ type: 'exact', text: 'a\nb' }, v), true);
});

test('goals: collect needs every coin', () => {
  const v = new Vim({ text: '$a$' });
  const col = new Set<number>([0]);
  assert.equal(checkGoal({ type: 'collect', char: '$' }, v, col), false);
  col.add(2);
  assert.equal(checkGoal({ type: 'collect', char: '$' }, v, col), true);
  assert.equal(collectPositions('$a$', '$').length, 2);
});

test('goal labels are bilingual', () => {
  assert.match(goalLabel({ type: 'reach', char: '*' }, 'ko'), /\*/);
  assert.match(goalLabel({ type: 'reach', char: '*' }, 'en'), /Reach/);
});

const stage: Stage = {
  id: 't1',
  name: { en: 't', ko: 't' },
  brief: { en: 't', ko: 't' },
  text: '@..*',
  goal: { type: 'reach', char: '*' },
  par: 3,
  solution: '3l',
};

test('session counts keys and awards stars', () => {
  const s = new Session({ stage, chapterIndex: 0, allowed: new Set(['l']) });
  s.feed('l');
  assert.equal(s.status, 'playing');
  s.feed('l');
  s.feed('l');
  assert.equal(s.status, 'won');
  assert.equal(s.keys, 3);
  assert.equal(s.stars, 3);
});

test('failed undo/redo clears the pending command display', () => {
  const v = new Vim({ text: 'abc' });
  v.feedString('u');
  assert.equal(v.pendingCommand, '');
  assert.equal(v.awaitingKey, false);

  const w = new Vim({ text: 'abc' });
  w.feedString('3u');
  assert.equal(w.pendingCommand, '');
  assert.equal(w.awaitingKey, false);

  const r = new Vim({ text: 'abc' });
  r.feedString('3<C-r>');
  assert.equal(r.pendingCommand, '');
  assert.equal(r.awaitingKey, false);
});

test('demo playback moves the vim but never wins or counts keys', () => {
  const s = new Session({ stage, chapterIndex: 0, allowed: new Set(['l']) });
  s.demo = true;
  s.feed('l');
  s.feed('l');
  s.feed('l');
  assert.equal(s.status, 'playing');
  assert.equal(s.keys, 0);
  assert.equal(s.vim.cursor.col, 3);
});

test('session gate blocks locked keys without counting them', () => {
  const s = new Session({ stage, chapterIndex: 0, allowed: new Set(['l']) });
  const ok = s.feed('d');
  assert.equal(ok, false);
  assert.equal(s.keys, 0);
});

test('session hazard costs a heart once per tile', () => {
  const st: Stage = { ...stage, text: '~ ~*', goal: { type: 'reach', char: '*' }, par: 5, solution: 'lllll' };
  const s = new Session({ stage: st, chapterIndex: 0, allowed: new Set(['l']) });
  s.feed('l');
  assert.equal(s.hearts, 3);
  s.feed('l');
  assert.equal(s.hearts, 2);
  s.feed('h');
  s.feed('l');
  assert.equal(s.hearts, 2, 'the same tile should only bite once');
  assert.equal(s.status, 'playing');
});

