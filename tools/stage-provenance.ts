/**
 * Generate the stage-level provenance worksheet. It intentionally marks every
 * stage as `unmapped`: the sheet must not pretend that a book citation audit
 * has happened. Fill a row only after reading the cited section.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { CHAPTERS } from '../src/content/chapters/index.ts';
import { COMMAND_BY_ID } from '../src/content/commands.ts';

const overlayPath = new URL('../books-index/curriculum-map/stages.json', import.meta.url);
const overlay = existsSync(overlayPath) ? (JSON.parse(readFileSync(overlayPath, 'utf8')) as { stages: { stage: string; tips: { book: string; tip: number; line: number; title: string }[]; supplement: { book: string; line: number; evidence: string }[] }[] }).stages : [];
const sourceByStage = new Map(overlay.map((x) => [x.stage, x]));

const lines = [
  '# STAGE PROVENANCE — worksheet (not an audit result)',
  '',
  '> Generated by `npm run provenance` from the stage data. A row is',
  '> `unmapped` unless it carries a real source. The summary at the bottom is',
  '> generated from the current stage data. A row may become `cited` only when it has a',
  '> `book → section → command/tip` citation from [`BOOKS_INDEX.md`](BOOKS_INDEX.md),',
  '> a prerequisite check and a varied-repetition plan. See',
  '> [`CURRICULUM_PROVENANCE.md`](CURRICULUM_PROVENANCE.md).',
  '',
  '| stage | chapter | teaches | par | source section | drill / transfer | status |',
  '|---|---:|---|---:|---|---|---|',
];

let cited = 0;
let unmapped = 0;
for (const ch of CHAPTERS) {
  for (const st of ch.stages) {
    const teaches = (st.teaches ?? []).map((id) => COMMAND_BY_ID.get(id)?.keys ?? id).join(' ');
    const ov = sourceByStage.get(st.id);
    const src = ov
      ? [
          ...ov.tips.map((t) => `${t.book} — Tip ${t.tip}, “${t.title}” (line ${t.line})`),
          ...ov.supplement.map((x) => `${x.book} — line ${x.line} — ${x.evidence}`),
        ].join('<br>')
      : (st.sources ?? []).map((x) => `${x.book} — ${x.section}`).join('<br>');
    const status = src ? 'cited' : 'unmapped';
    if (src) cited++;
    else unmapped++;
    lines.push(`| ${st.id} | ${ch.index} | \`${teaches}\` | ${st.par} | ${src || 'TODO'} | TODO | ${status} |`);
  }
}

lines.push(
  '',
  `Summary: **${cited} cited**, **${unmapped} unmapped** of 51. A cited row\nstill needs a prerequisite check and a varied-repetition plan.`,
  '',
  '## How to fill a row',
  '',
  '1. Find the section in `BOOKS_INDEX.md`; cite the book + section + line.',
  '2. Check the concept appears after its prerequisites.',
  '3. Record the varied repetition plan (text/cursor/count/operator/nest/medium).',
  '4. Keep one insight per stage; do not add stages in this program.',
  '',
);
writeFileSync(new URL('../docs/STAGE_PROVENANCE.md', import.meta.url), lines.join('\n'));
console.log(`stage provenance worksheet: ${CHAPTERS.reduce((n, c) => n + c.stages.length, 0)} stages -> docs/STAGE_PROVENANCE.md`);
